package twitter4j

// Note: this class was written without inspecting the non-free org.json sourcecode.

/**
 * Parses a JSON (RFC 4627) encoded string into the corresponding object. Most
 * clients of this class will only need the [JSONTokener] constructor and
 * [nextValue] method. Example usage:
 * ```
 * JSONObject object = (JSONObject) new JSONTokener(json).nextValue();
 * String query = object.getString("query");
 * JSONArray locations = object.getJSONArray("locations");
 * ```
 *
 * For best interoperability and performance use JSON that complies with
 * RFC 4627, such as that generated by [JSONStringer]. For legacy reasons
 * this parser is lenient, so a successful parse does not indicate that the
 * input string was valid JSON.
 *
 * Each tokener may be used to parse a single JSON string. Instances of this
 * class are not thread safe.
 *
 * KMP対応: 元は Reader/InputStream ベースのコンストラクタ（java.io 依存）も持っていたが、
 * どこからも参照されていないため削除し、String（文字列 + インデックス）ベースのみとした。
 */
class JSONTokener(in0: String?) {

    /**
     * The input JSON.
     */
    private val input: String?

    /**
     * The index of the next character to be returned by [next]. When
     * the input is exhausted, this equals the input's length.
     */
    private var pos = 0

    init {
        // consume an optional byte order mark (BOM) if it exists
        var s = in0
        if (s != null && s.startsWith("\uFEFF")) {
            s = s.substring(1)
        }
        input = s
    }

    /**
     * Returns the next value from the input.
     *
     * @return a [JSONObject], [JSONArray], String, Boolean,
     * Integer, Long, Double or [JSONObject.NULL].
     * @throws JSONException if the input is malformed.
     */
    fun nextValue(): Any? {
        val c = nextCleanInternal()
        return when (c) {
            -1 -> throw syntaxError("End of input")

            '{'.code -> readObject()

            '['.code -> readArray()

            '\''.code, '"'.code -> nextString(c.toChar())

            else -> {
                pos--
                readLiteral()
            }
        }
    }

    private fun nextCleanInternal(): Int {
        while (pos < input!!.length) {
            val c = input!![pos++].code
            when (c) {
                '\t'.code, ' '.code, '\n'.code, '\r'.code -> continue

                '/'.code -> {
                    if (pos == input!!.length) {
                        return c
                    }

                    val peek = input!![pos]
                    when (peek) {
                        '*' -> {
                            // skip a /* c-style comment */
                            pos++
                            val commentEnd = input!!.indexOf("*/", pos)
                            if (commentEnd == -1) {
                                throw syntaxError("Unterminated comment")
                            }
                            pos = commentEnd + 2
                            continue
                        }

                        '/' -> {
                            // skip a // end-of-line comment
                            pos++
                            skipToEndOfLine()
                            continue
                        }

                        else -> return c
                    }
                }

                '#'.code -> {
                    /*
                     * Skip a # hash end-of-line comment. The JSON RFC doesn't
                     * specify this behavior, but it's required to parse
                     * existing documents. See http://b/2571423.
                     */
                    skipToEndOfLine()
                    continue
                }

                else -> return c
            }
        }

        return -1
    }

    /**
     * Advances the position until after the next newline character. If the line
     * is terminated by "\r\n", the '\n' must be consumed as whitespace by the
     * caller.
     */
    private fun skipToEndOfLine() {
        while (pos < input!!.length) {
            val c = input!![pos]
            if (c == '\r' || c == '\n') {
                pos++
                break
            }
            pos++
        }
    }

    /**
     * Returns the string up to but not including `quote`, unescaping any
     * character escape sequences encountered along the way. The opening quote
     * should have already been read. This consumes the closing quote, but does
     * not include it in the returned string.
     *
     * @param quote either ' or ".
     * @return The unescaped string.
     * @throws JSONException if the string isn't terminated by a closing quote correctly.
     */
    fun nextString(quote: Char): String {
        /*
         * For strings that are free of escape sequences, we can just extract
         * the result as a substring of the input. But if we encounter an escape
         * sequence, we need to use a StringBuilder to compose the result.
         */
        var builder: StringBuilder? = null

        /* the index of the first character not yet appended to the builder. */
        var start = pos

        while (pos < input!!.length) {
            val c = input!![pos++]
            if (c == quote) {
                return if (builder == null) {
                    input!!.substring(start, pos - 1)
                } else {
                    builder.append(input, start, pos - 1)
                    builder.toString()
                }
            }

            if (c == '\\') {
                if (pos == input!!.length) {
                    throw syntaxError("Unterminated escape sequence")
                }
                if (builder == null) {
                    builder = StringBuilder()
                }
                builder.append(input, start, pos - 1)
                builder.append(readEscapeCharacter())
                start = pos
            }
        }

        throw syntaxError("Unterminated string")
    }

    /**
     * Unescapes the character identified by the character or characters that
     * immediately follow a backslash. The backslash '\' should have already
     * been read. This supports both unicode escapes "u000A" and two-character
     * escapes "\n".
     */
    private fun readEscapeCharacter(): Char {
        val escaped = input!![pos++]
        when (escaped) {
            'u' -> {
                if (pos + 4 > input!!.length) {
                    throw syntaxError("Unterminated escape sequence")
                }
                val hex = input!!.substring(pos, pos + 4)
                pos += 4
                return try {
                    hex.toInt(16).toChar()
                } catch (nfe: NumberFormatException) {
                    throw syntaxError("Invalid escape sequence: $hex")
                }
            }

            't' -> return '\t'

            'b' -> return '\b'

            'n' -> return '\n'

            'r' -> return '\r'

            'f' -> return '\u000C'

            // covers '\'', '"', '\\', and the default case
            else -> return escaped
        }
    }

    /**
     * Reads a null, boolean, numeric or unquoted string literal value. Numeric
     * values will be returned as an Integer, Long, or Double, in that order of
     * preference.
     */
    private fun readLiteral(): Any {
        val literal = nextToInternal("{}[]/\\:,=;# \t\u000C")

        if (literal.isEmpty()) {
            throw syntaxError("Expected literal value")
        } else if ("null".equals(literal, ignoreCase = true)) {
            return JSONObject.NULL
        } else if ("true".equals(literal, ignoreCase = true)) {
            return true
        } else if ("false".equals(literal, ignoreCase = true)) {
            return false
        }

        /* try to parse as an integral type... */
        if (literal.indexOf('.') == -1) {
            var base = 10
            var number = literal
            if (number.startsWith("0x") || number.startsWith("0X")) {
                number = number.substring(2)
                base = 16
            } else if (number.startsWith("0") && number.length > 1) {
                number = number.substring(1)
                base = 8
            }
            try {
                val longValue = number.toLong(base)
                return if (longValue <= Int.MAX_VALUE && longValue >= Int.MIN_VALUE) {
                    longValue.toInt()
                } else {
                    longValue
                }
            } catch (e: NumberFormatException) {
                /*
                 * This only happens for integral numbers greater than
                 * Long.MAX_VALUE, numbers in exponential form (5e-10) and
                 * unquoted strings. Fall through to try floating point.
                 */
            }
        }

        /* ...next try to parse as a floating point... */
        val d = literal.toDoubleOrNull()
        if (d != null) {
            return d
        }

        /* ... finally give up. We have an unquoted string */
        return literal
    }

    /**
     * Returns the string up to but not including any of the given characters or
     * a newline character. This does not consume the excluded character.
     */
    private fun nextToInternal(excluded: String): String {
        val start = pos
        while (pos < input!!.length) {
            val c = input!![pos]
            if (c == '\r' || c == '\n' || excluded.indexOf(c) != -1) {
                return input!!.substring(start, pos)
            }
            pos++
        }
        return input!!.substring(start)
    }

    /**
     * Reads a sequence of key/value pairs and the trailing closing brace '}' of
     * an object. The opening brace '{' should have already been read.
     */
    private fun readObject(): JSONObject {
        val result = JSONObject()

        /* Peek to see if this is the empty object. */
        val first = nextCleanInternal()
        if (first == '}'.code) {
            return result
        } else if (first != -1) {
            pos--
        }

        while (true) {
            val name = nextValue()
            if (name !is String) {
                if (name == null) {
                    throw syntaxError("Names cannot be null")
                } else {
                    throw syntaxError(
                        "Names must be strings, but " + name
                                + " is of type " + name::class.simpleName
                    )
                }
            }

            /*
             * Expect the name/value separator to be either a colon ':', an
             * equals sign '=', or an arrow "=>". The last two are bogus but we
             * include them because that's what the original implementation did.
             */
            val separator = nextCleanInternal()
            if (separator != ':'.code && separator != '='.code) {
                throw syntaxError("Expected ':' after $name")
            }
            if (pos < input!!.length && input!![pos] == '>') {
                pos++
            }

            result.put(name, nextValue())

            when (nextCleanInternal()) {
                '}'.code -> return result
                ';'.code, ','.code -> continue
                else -> throw syntaxError("Unterminated object")
            }
        }
    }

    /**
     * Reads a sequence of values and the trailing closing brace ']' of an
     * array. The opening brace '[' should have already been read. Note that
     * "[]" yields an empty array, but "[,]" returns a two-element array
     * equivalent to "[null,null]".
     */
    private fun readArray(): JSONArray {
        val result = JSONArray()

        /* to cover input that ends with ",]". */
        var hasTrailingSeparator = false

        while (true) {
            when (nextCleanInternal()) {
                -1 -> throw syntaxError("Unterminated array")
                ']'.code -> {
                    if (hasTrailingSeparator) {
                        result.put(null)
                    }
                    return result
                }
                ','.code, ';'.code -> {
                    /* A separator without a value first means "null". */
                    result.put(null)
                    hasTrailingSeparator = true
                    continue
                }
                else -> pos--
            }

            result.put(nextValue())

            when (nextCleanInternal()) {
                ']'.code -> return result
                ','.code, ';'.code -> {
                    hasTrailingSeparator = true
                    continue
                }
                else -> throw syntaxError("Unterminated array")
            }
        }
    }

    /**
     * Returns an exception containing the given message plus the current
     * position and the entire input string.
     *
     * @param message The message we want to include.
     * @return An exception that we can throw.
     */
    fun syntaxError(message: String): JSONException {
        return JSONException(message + this)
    }

    /**
     * Returns the current position and the entire input string.
     */
    override fun toString(): String {
        // consistent with the original implementation
        return " at character $pos of $input"
    }

    /*
     * Legacy APIs.
     *
     * None of the methods below are on the critical path of parsing JSON
     * documents. They exist only because they were exposed by the original
     * implementation and may be used by some clients.
     */

    /**
     * Returns true until the input has been exhausted.
     */
    fun more(): Boolean {
        return pos < input!!.length
    }

    /**
     * Returns the next available character, or the null character '\0' if all
     * input has been exhausted.
     */
    fun next(): Char {
        return if (pos < input!!.length) input!![pos++] else '\u0000'
    }

    /**
     * Returns the next available character if it equals `c`. Otherwise an
     * exception is thrown.
     */
    fun next(c: Char): Char {
        val result = next()
        if (result != c) {
            throw syntaxError("Expected $c but was $result")
        }
        return result
    }

    /**
     * Returns the next character that is not whitespace and does not belong to
     * a comment. If the input is exhausted before such a character can be
     * found, the null character '\0' is returned.
     */
    fun nextClean(): Char {
        val nextCleanInt = nextCleanInternal()
        return if (nextCleanInt == -1) '\u0000' else nextCleanInt.toChar()
    }

    /**
     * Returns the next `length` characters of the input.
     */
    fun next(length: Int): String {
        if (pos + length > input!!.length) {
            throw syntaxError("$length is out of bounds")
        }
        val result = input!!.substring(pos, pos + length)
        pos += length
        return result
    }

    /**
     * Returns the trimmed string holding the characters up to but not including
     * the first of: any character in `excluded`, a newline '\n', or a carriage
     * return '\r'.
     */
    fun nextTo(excluded: String?): String {
        if (excluded == null) {
            throw NullPointerException("excluded == null")
        }
        return nextToInternal(excluded).trim()
    }

    /**
     * Equivalent to `nextTo(String.valueOf(excluded))`.
     */
    fun nextTo(excluded: Char): String {
        return nextToInternal(excluded.toString()).trim()
    }

    /**
     * Advances past all input up to and including the next occurrence of
     * `thru`. If the remaining input doesn't contain `thru`, the input is
     * exhausted.
     */
    fun skipPast(thru: String) {
        val thruStart = input!!.indexOf(thru, pos)
        pos = if (thruStart == -1) input!!.length else thruStart + thru.length
    }

    /**
     * Advances past all input up to but not including the next occurrence of
     * `to`. If the remaining input doesn't contain `to`, the input is
     * unchanged.
     */
    fun skipTo(to: Char): Char {
        val index = input!!.indexOf(to, pos)
        return if (index != -1) {
            pos = index
            to
        } else {
            '\u0000'
        }
    }

    /**
     * Unreads the most recent character of input. If no input characters have
     * been read, the input is unchanged.
     */
    fun back() {
        if (--pos == -1) {
            pos = 0
        }
    }

    companion object {
        /**
         * Returns the integer [0..15] value for the given hex character, or -1
         * for non-hex input.
         */
        @JvmStatic
        fun dehexchar(hex: Char): Int {
            return when (hex) {
                in '0'..'9' -> hex - '0'
                in 'A'..'F' -> hex - 'A' + 10
                in 'a'..'f' -> hex - 'a' + 10
                else -> -1
            }
        }
    }
}
